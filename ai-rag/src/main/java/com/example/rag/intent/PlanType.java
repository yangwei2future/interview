package com.example.rag.intent;

/**
 * 规划类型枚举。
 *
 * <p>判断标准不是"一条SQL能不能搞定"，
 * 而是"所需信息在开始之前是否已全部确定"。</p>
 */
public enum PlanType {

    /**
     * 一次性规划：目标明确，不需要中间结果来修正方向。
     *
     * <p>适用场景：
     * <ul>
     *   <li>问题目标、对象、时间范围全部确定</li>
     *   <li>你知道该查哪些数据，只是不知道在哪个表、哪个字段</li>
     *   <li>示例："2026年理想L6的销量是多少？"、"昨天GMV多少"</li>
     * </ul>
     */
    SINGLE_TURN,

    /**
     * 动态规划：需要先探索，根据中间结果决定下一步做什么。
     *
     * <p>适用场景：
     * <ul>
     *   <li>问题目标模糊，需要先探索再确定</li>
     *   <li>涉及多实体对比，对比结果影响后续步骤</li>
     *   <li>涉及因果分析（"为什么"类问题）</li>
     *   <li>示例："为什么理想L6销量下降了？"、"哪个车型增长最快？"</li>
     * </ul>
     */
    MULTI_TURN
}
